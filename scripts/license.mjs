#!/usr/bin/env node
// Vendor-side license tool. Keep license-keys/private.jwk.json secret and backed up.
//   npm run license:keys                         → create key pair, writes public key into the app
//   npm run license:issue -- --company "ACME TRS" --users 50 --expires 2027-12-31 [--plan Enterprise] [--modules ops,field]
import { webcrypto as crypto } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { randomUUID } from 'node:crypto';

const DIR = 'license-keys';
const PRIV = `${DIR}/private.jwk.json`;
const b64url = (buf) => Buffer.from(buf).toString('base64url');

const [cmd, ...rest] = process.argv.slice(2);
const args = {};
for (let i = 0; i < rest.length; i += 2) args[rest[i].replace(/^--/, '')] = rest[i + 1];

if (cmd === 'keys') {
  if (existsSync(PRIV) && args.force !== 'yes') {
    console.error(`${PRIV} already exists. Re-run with --force yes to replace it (old licenses will stop working).`);
    process.exit(1);
  }
  const kp = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify']);
  const priv = await crypto.subtle.exportKey('jwk', kp.privateKey);
  const pub = await crypto.subtle.exportKey('jwk', kp.publicKey);
  mkdirSync(DIR, { recursive: true });
  writeFileSync(PRIV, JSON.stringify(priv, null, 2));
  writeFileSync(
    'src/lib/licensePublicKey.ts',
    `// Generated by \`npm run license:keys\` on ${new Date().toISOString()}\nexport const LICENSE_PUBLIC_KEY: JsonWebKey | null = ${JSON.stringify({ kty: pub.kty, crv: pub.crv, x: pub.x, y: pub.y })};\n`,
  );
  console.log(`Private key: ${PRIV}  (KEEP SECRET, never commit)\nPublic key written to src/lib/licensePublicKey.ts`);
} else if (cmd === 'issue') {
  if (!args.company || !args.expires) {
    console.error('Usage: npm run license:issue -- --company "Company Name" --expires YYYY-MM-DD [--users 25] [--plan Standard] [--modules *]');
    process.exit(1);
  }
  const jwk = JSON.parse(readFileSync(PRIV, 'utf8'));
  const key = await crypto.subtle.importKey('jwk', jwk, { name: 'ECDSA', namedCurve: 'P-256' }, false, ['sign']);
  const payload = {
    company: args.company,
    licenseId: randomUUID(),
    plan: args.plan ?? 'Standard',
    maxUsers: Number(args.users ?? 25),
    modules: (args.modules ?? '*').split(','),
    issued: new Date().toISOString().slice(0, 10),
    expires: args.expires,
  };
  const head = `TRS1.${b64url(JSON.stringify(payload))}`;
  const sig = await crypto.subtle.sign({ name: 'ECDSA', hash: 'SHA-256' }, key, new TextEncoder().encode(head));
  console.log(JSON.stringify(payload, null, 2));
  console.log(`\nLICENSE KEY:\n${head}.${b64url(sig)}`);
} else {
  console.log('Commands: keys | issue');
}
